import fs from "node:fs";
import path from "node:path";

// Source of truth: what is pushed to the au-themes repo
// AU_THEMES_DIR reads a local clone instead, to preview it
const UPSTREAM = "szymonwilczek/au-themes";
const UPSTREAM_BRANCH = "main";
const FETCH_TIMEOUT_MS = 20000;
const THEME_FILE = /^au-.+-theme\.el$/;
const LOCAL_DIR = process.env.AU_THEMES_DIR && path.resolve(process.env.AU_THEMES_DIR);
const CSS_OUT = "src/styles/au-themes.css";
const MORE_OUT = "src/styles/au-themes-more.css";
const JSON_OUT = "src/data/au-themes.json";

const FAMILY_ORDER = ["salina"];
const VARIANT_ORDER = ["morning", "day", "night"];
const DEFAULT_THEMES = { light: "salina-day", dark: "salina-night" };

async function upstreamGet(url) {
  const token = process.env.GITHUB_TOKEN;
  const response = await fetch(url, {
    headers: token ? { authorization: `Bearer ${token}` } : {},
    signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
  });
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response;
}

// Pinned to the commit: branch urls on raw.githubusercontent.com lag behind a push
async function readUpstream() {
  const api = `https://api.github.com/repos/${UPSTREAM}`;
  const commit = await (await upstreamGet(`${api}/commits/${UPSTREAM_BRANCH}`)).json();
  const tree = await (await upstreamGet(`${api}/git/trees/${commit.sha}`)).json();
  const sources = await Promise.all(
    tree.tree
      .map((entry) => entry.path)
      .filter((file) => THEME_FILE.test(file))
      .map(async (file) => {
        const raw = `https://raw.githubusercontent.com/${UPSTREAM}/${commit.sha}/${file}`;
        return { file, source: await (await upstreamGet(raw)).text() };
      }),
  );
  return { origin: `${UPSTREAM}@${commit.sha.slice(0, 7)}`, sources };
}

function readLocal(directory) {
  if (!fs.existsSync(directory)) {
    throw new Error(`au-themes not found at ${directory}`);
  }
  const sources = fs
    .readdirSync(directory)
    .filter((file) => THEME_FILE.test(file))
    .map((file) => ({ file, source: fs.readFileSync(path.join(directory, file), "utf8") }));
  return { origin: directory, sources };
}

function parseTheme({ file, source }) {
  const name = file.replace(/-theme\.el$/, "");
  const id = name.replace(/^au-/, "");
  const [family, ...rest] = id.split("-");
  const variant = rest.join("-");

  const partial = source.match(/-palette-partial\s+'\(([\s\S]*?)\)\)\)/);
  const mappings = source.match(/-palette-mappings-partial\s+'\(([\s\S]*?)\)\)\)/);
  const meta = source.match(/\(modus-themes-theme\s+'\S+\s+'\S+\s+"([^"]*)"\s+'(light|dark)/);
  if (!partial || !mappings || !meta) {
    throw new Error(`${file}: unrecognised theme layout`);
  }

  const colors = new Map();
  for (const [, key, hex] of partial[1].matchAll(/\(([a-z0-9-]+)\s+"(#[0-9a-fA-F]{6})"\)/g)) {
    colors.set(key, hex.toLowerCase());
  }

  // Semantic mappings point at palette entries (or at each other); resolve to hex
  const aliases = new Map();
  for (const [, key, target] of mappings[1].matchAll(/\(([a-z0-9-]+)\s+([a-z0-9-]+)\)/g)) {
    aliases.set(key, target);
  }
  const resolve = (key, seen = new Set()) => {
    if (colors.has(key)) return colors.get(key);
    if (!aliases.has(key) || seen.has(key)) return null;
    seen.add(key);
    return resolve(aliases.get(key), seen);
  };
  for (const key of aliases.keys()) {
    const hex = resolve(key);
    if (hex) colors.set(key, hex);
    else console.warn(`  ${id}: unresolved mapping ${key} -> ${aliases.get(key)}`);
  }

  return { id, family, variant, polarity: meta[2], description: meta[1], colors };
}

function rank(list, value) {
  const i = list.indexOf(value);
  return i === -1 ? list.length : i;
}

function compareThemes(former, latter) {
  return (
    rank(FAMILY_ORDER, former.family) - rank(FAMILY_ORDER, latter.family) ||
    former.family.localeCompare(latter.family) ||
    rank(VARIANT_ORDER, former.variant) - rank(VARIANT_ORDER, latter.variant)
  );
}

const HEADER =
  "/* Generated by scripts/build-themes.mjs from au-themes. Do not edit by hand. */\n\n";

const isDefault = (theme) => Object.values(DEFAULT_THEMES).includes(theme.id);

function renderBlocks(themes) {
  return themes.map((theme) => {
    const vars = [...theme.colors].map(([key, hex]) => `  --${key}: ${hex};`);
    return [
      `:root[data-theme="${theme.id}"] {`,
      `  color-scheme: ${theme.polarity};`,
      ...vars,
      "}",
    ].join("\n");
  });
}

function renderCss(themes) {
  const blocks = renderBlocks(themes.filter(isDefault));
  // Without the boot script (no JS), follow the system with the default pair.
  const byId = new Map(themes.map((theme) => [theme.id, theme]));
  const fallback = (id, indent) => {
    const theme = byId.get(id);
    const pad = " ".repeat(indent);
    return [
      `${pad}:root:not([data-theme]) {`,
      `${pad}  color-scheme: ${theme.polarity};`,
      ...[...theme.colors].map(([key, hex]) => `${pad}  --${key}: ${hex};`),
      `${pad}}`,
    ].join("\n");
  };
  blocks.push(fallback(DEFAULT_THEMES.dark, 0));
  blocks.push(
    ["@media (prefers-color-scheme: light) {", fallback(DEFAULT_THEMES.light, 2), "}"].join("\n"),
  );
  return HEADER + blocks.join("\n\n") + "\n";
}

function renderMoreCss(themes) {
  return HEADER + renderBlocks(themes.filter((theme) => !isDefault(theme))).join("\n\n") + "\n";
}

function renderJson(themes) {
  const entries = themes.map(({ id, family, variant, polarity, description, colors }) => ({
    id,
    family,
    variant,
    polarity,
    description,
    swatch: [colors.get("bg-main"), colors.get("fg-main"), colors.get("cursor"), colors.get("red")],
  }));
  return JSON.stringify(entries, null, 2) + "\n";
}

const { origin, sources } = LOCAL_DIR ? readLocal(LOCAL_DIR) : await readUpstream();
const themes = sources.map(parseTheme).sort(compareThemes);

fs.mkdirSync(path.dirname(JSON_OUT), { recursive: true });
fs.writeFileSync(CSS_OUT, renderCss(themes));
fs.writeFileSync(MORE_OUT, renderMoreCss(themes));
fs.writeFileSync(JSON_OUT, renderJson(themes));

console.log(`Generated ${themes.length} themes from ${origin}`);
for (const theme of themes) {
  console.log(`  ${theme.id.padEnd(22)} ${theme.polarity.padEnd(5)} ${theme.colors.size} tokens`);
}
